class DataStore {
  constructor() {
    this.data = null;
    this.init();
  }

  init() {
    if (fs.existsSync(DATA_FILE)) {
      try {
        const raw = fs.readFileSync(DATA_FILE, 'utf-8');
        this.data = JSON.parse(raw);
        if (!this.data.users || this.data.users.length === 0) {
          console.log('Users array missing in store.json, seeding baseline admin account...');
          this.data = generateSeedData();
          this.save();
        } else if (!this.data.employees || this.data.employees.length === 0) {
          console.log('Employees array missing or empty, seeding 10 staff profiles...');
          const seed = generateSeedData();
          this.data.employees = seed.employees;
          this.save();
        }
      } catch (err) {
        console.error('Error parsing existing store.json, re-seeding:', err.message);
        this.data = generateSeedData();
        this.save();
      }
    } else {
      this.data = generateSeedData();
      this.save();
    }
  }

  save() {
    try {
      fs.writeFileSync(DATA_FILE, JSON.stringify(this.data, null, 2), 'utf-8');
    } catch (err) {
      console.error('Error saving data store:', err.message);
    }
  }

  // Generic getter
  getCollection(name) {
    if (!this.data[name]) {
      this.data[name] = [];
    }
    return this.data[name];
  }

  // Update a collection item
  updateItem(collection, id, updates) {
    const items = this.getCollection(collection);
    const index = items.findIndex((i) => i.id === id);
    if (index !== -1) {
      items[index] = { ...items[index], ...updates, updatedAt: new Date().toISOString() };
      this.save();
      return items[index];
    }
    return null;
  }

  // Add item
  addItem(collection, item) {
    const items = this.getCollection(collection);
    const newItem = {
      id: item.id || `${collection.slice(0, 3)}-${Date.now()}`,
      ...item,
      createdAt: item.createdAt || new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };
    items.unshift(newItem);
    this.save();
    return newItem;
  }

  // Remove item
  removeItem(collection, id) {
    const items = this.getCollection(collection);
    const index = items.findIndex((i) => i.id === id);
    if (index !== -1) {
      const removed = items.splice(index, 1)[0];
      this.save();
      return removed;
    }
    return null;
  }

  // Reset to initial seed
  reset() {
    this.data = generateSeedData();
    this.save();
    return this.data;
  }
}

const store = new DataStore();

module.exports = { store, generateSeedData };

